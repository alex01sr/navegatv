import { createRequire } from 'module';
const require = createRequire('/Users/alexanderreyes/.npm/_npx/9833c18b2d85bc59/node_modules/');
const { chromium } = require('playwright');
import fs from 'fs';
const code = fs.readFileSync('../dist/navegatv.js','utf8');
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1920, height: 1080 } });
await ctx.addInitScript(code);
const page = await ctx.newPage();
let dialogs = 0; page.on('dialog', d => { dialogs++; d.dismiss(); });
await page.goto('http://localhost:8001/focus.html'); await page.waitForTimeout(1000);
await page.evaluate(()=>{ document.getElementById('sw').click(); });
const right = await page.evaluate(()=>document.activeElement.tagName);
await page.waitForTimeout(1300);
const after = await page.evaluate(()=>document.activeElement.tagName);
await page.keyboard.press('Escape'); await page.waitForTimeout(200);
const menu = await page.evaluate(()=>document.getElementById('ntv-host').shadowRoot.getElementById('menu').classList.contains('on'));
console.log(JSON.stringify({focusJustAfter: right, focusAfter1s: after, nativeDialogs: dialogs, backOpensMenu: menu}));
await browser.close();
